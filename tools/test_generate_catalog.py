import json
import unittest

import generate_catalog as g


class CatalogTests(unittest.TestCase):
    def test_built_catalog_is_valid(self):
        catalog = g.build()
        self.assertEqual(g.problems(catalog), [])
        self.assertEqual(catalog["schemaVersion"], 1)
        self.assertEqual(catalog["repo"], "rzvdaniel/automaton-monster")
        self.assertTrue(any(app["id"] == "untranslatable" for app in catalog["apps"]))

    def test_apps_that_left_the_official_catalog_say_where_they_came_from(self):
        apps = {a["id"]: a for a in g.build()["apps"]}
        self.assertEqual(apps["goatcounter"]["movedFrom"], {"repo": g.OFFICIAL_REPO, "folder": "analytics/goatcounter"})
        self.assertNotIn("movedFrom", apps["untranslatable"])

    def test_the_store_recommends_nothing(self):
        self.assertFalse(any("recommended" in app for app in g.build()["apps"]))

    def test_problems_report_bad_entries(self):
        bad = {"apps": [{"id": "x", "name": "X", "summary": "", "category": "C", "folder": "a/b", "commit": "abc", "minServerVersion": "1"}]}
        self.assertEqual(len(g.problems(bad)), 3)

    def test_folder_names_servers_would_reject_are_reported(self):
        bad = {"apps": [{"id": "x", "name": "X", "summary": "s", "category": "C", "folder": "a/./b", "commit": "a" * 40, "minServerVersion": "1.2.3"}]}
        self.assertEqual(len(g.problems(bad)), 1)

    def test_committed_catalog_is_valid_and_lives_at_the_repository_root(self):
        committed = g.ROOT / "catalog.json"
        if not committed.exists():  # the first catalog.json is written by CI after the first merge
            self.skipTest("catalog.json is generated by CI after the first merge")
        catalog = json.loads(committed.read_text(encoding="utf-8"))
        self.assertEqual(catalog["schemaVersion"], 1)
        self.assertEqual(g.problems(catalog), [])


if __name__ == "__main__":
    unittest.main()
